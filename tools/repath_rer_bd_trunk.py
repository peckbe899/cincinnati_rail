"""RER-2 (B) and RER-4 (D) between the Mill Creek trunk and Union Terminal onto the Mill Creek Deck's B/D route
(Ben, 2026-10-27: "RER tracks from Straight to CUT ... that is not what the deck artifact tracks look like").

The Profiles paths were the old KMZ line west of the trunk, up to 237 m off the Deck's route, which runs B and D
on the north viaduct (Arlington, Camp Washington), into the Straight box, through the twin bores to Western and
into the Union Terminal TRI box from the north (data/deck/context.json, push of 26 October 2026):

- RER-2: R-B-712689-4336858 (B from the B/D junction to Ludlow), R-BD-712316-4334957 (B/D to the box), the box
  axis, joining the old path at the east end of the box (R-B-713144-4331855, already on it).
- RER-4: R-AD-713024-4331860 (A/D, already on the old path to its west end), the box axis, R-BD-712316-4334957,
  R-D-710306-4337028 (D to the Indianapolis deck curve), joining the old path where the Deck's D does.

Each line keeps its chainage up to the first Deck vertex that lies within 0.5 m of its path and past the last;
chainages past the section move by the difference in length, chainages inside it are stretched (written to
data/profile/rer/repath_bd_trunk.json, which the Station 3D sync uses to move saved profiles made on the old
paths). Ground re-sampled from the map 3 raster, the section's stations moved to the Deck's station points,
crossings recomputed, plan networks and the line index updated, the repo's saved RER-2 profile shifted.
RER-4's profile is regenerated by tools/make_rer4_upper.py afterwards. Refuses to run on re-pathed lines.

    python tools/repath_rer_bd_trunk.py && python tools/make_rer4_upper.py
"""
import copy
import glob
import json
import math
import sys

import numpy as np
from shapely.geometry import LineString, Point

# shared helpers, as tools/repath_line3_norwood.py
from pathlib import Path
from pyproj import Transformer
import rasterio
from rasterio.windows import Window
ROOT = Path(__file__).resolve().parent.parent
SITE, DECK = str(ROOT / "data" / "profile"), str(ROOT / "data" / "deck")
ORIG = SITE
VRT = str(ROOT / "data" / "profile" / "dem" / "map3_profile_dem_dm.vrt")
TO_UTM = Transformer.from_crs(4326, 26916, always_xy=True)
TO_LL = Transformer.from_crs(26916, 4326, always_xy=True)
def jload(p): return json.load(open(p, encoding='utf8'))
def jsave(p, d, indent=None):
    with open(p, 'w', encoding='utf8') as f: json.dump(d, f, ensure_ascii=False, indent=indent, separators=(',', ':') if indent is None else None)
class Path:
    """A Profiles line path: vertices [c, lon, lat] -> UTM polyline with chainage mapping."""
    def __init__(self, path):
        self.cv = np.array([p[0] for p in path], float)
        self.xy = np.array([TO_UTM.transform(p[1], p[2]) for p in path])
        self.L = LineString(self.xy)
        seg = np.hypot(*np.diff(self.xy, axis=0).T); self.dv = np.concatenate([[0], np.cumsum(seg)])
    def c_of_d(self, d): return float(np.interp(d, self.dv, self.cv))
    def d_of_c(self, c): return float(np.interp(c, self.cv, self.dv))
    def chain(self, pt): return self.c_of_d(self.L.project(Point(pt)))
    def at(self, c): p = self.L.interpolate(self.d_of_c(c)); return (p.x, p.y)

_ds = rasterio.open(VRT)
def sample(xy, mode='bilinear'):
    """xy: array (n,2) UTM 16N (EPSG:26916). Returns metres (NaN for nodata)."""
    xy = np.asarray(xy, float)
    col = (xy[:, 0] - 695000.0) / 2.0 - 0.5; row = (4350000.0 - xy[:, 1]) / 2.0 - 0.5
    c0, r0 = int(np.floor(col.min())) - 2, int(np.floor(row.min())) - 2
    c1, r1 = int(np.ceil(col.max())) + 3, int(np.ceil(row.max())) + 3
    a = _ds.read(1, window=Window(c0, r0, c1 - c0, r1 - r0)).astype(float)
    a[a == -32768] = np.nan
    cc, rr = col - c0, row - r0
    if mode == 'nearest':
        return a[np.round(rr).astype(int), np.round(cc).astype(int)] / 10
    i, j = np.floor(rr).astype(int), np.floor(cc).astype(int); fr, fc = rr - i, cc - j
    v = (a[i, j] * (1 - fr) * (1 - fc) + a[i, j + 1] * (1 - fr) * fc + a[i + 1, j] * fr * (1 - fc) + a[i + 1, j + 1] * fr * fc)
    return v / 10


MAP = SITE + '/rer/repath_bd_trunk.json'
NEAR = 0.5   # a Deck vertex this close to the old path is on it


def deck_route(lid, R):
    if lid == 'RER_2':      # north to south
        return R['R-B-712689-4336858'] + R['R-BD-712316-4334957'][1:] + R['R-B-713144-4331855'][:1]
    return R['R-AD-713024-4331860'][::-1] + R['R-BD-712316-4334957'][::-1] + R['R-D-710306-4337028'][::-1][1:]


def section(route, P):
    """The Deck route between its first and last vertex on the old path, and the old chainages there."""
    on = [i for i, q in enumerate(route) if P.L.distance(Point(q)) < NEAR]
    a, b = on[0], on[-1]
    # the first vertex past which the route leaves the path, the last before it rejoins
    while a + 1 < len(route) and P.L.distance(Point(route[a + 1])) < NEAR:
        a += 1
    while b - 1 > a and P.L.distance(Point(route[b - 1])) < NEAR:
        b -= 1
    pts = [tuple(q) for q in route[a:b + 1]]
    ca, cb = P.chain(pts[0]), P.chain(pts[-1])
    pts[0], pts[-1] = P.at(ca), P.at(cb)   # exactly on the old path
    return pts, ca, cb


def main():
    if glob.glob(MAP):
        sys.exit(f'{MAP} exists: RER-2 and RER-4 are already on the Deck route')
    ctx = jload(DECK + '/context.json')
    R = {x['id']: x['c'] for x in ctx['rer']}
    dst = {s['name']: s['p'] for s in ctx['rer_stations'] if set(s['lines']) & {'B', 'D'}}
    files = sorted(glob.glob(SITE + '/lines/*_*.json')) + sorted(glob.glob(SITE + '/rer/lines/RER_*.json'))
    D = {fn: jload(fn) for fn in files}
    by_id = {d['id']: fn for fn, d in D.items()}
    oldP = {d['id']: Path(d['path']) for d in D.values()}
    sec, maps = {}, {}
    for lid in ('RER_2', 'RER_4'):
        pts, ca, cb = section(deck_route(lid, R), oldP[lid])
        dn = sum(math.dist(pts[i], pts[i - 1]) for i in range(1, len(pts)))
        sec[lid] = dict(pts=pts, ca=ca, cb=cb, dn=dn, delta=dn - (cb - ca), L0=D[by_id[lid]]['length_m'])
        maps[lid] = lambda c, s=sec[lid]: float(c if c <= s['ca'] else c + s['delta'] if c >= s['cb']
                                               else s['ca'] + (c - s['ca']) * s['dn'] / (s['cb'] - s['ca']))
        print(f"{lid}: old c {ca:.1f}-{cb:.1f} ({cb - ca:.1f} m) -> {dn:.1f} m on the Deck route, shift {sec[lid]['delta']:+.1f} m")
    insec = lambda lid, c: lid in sec and sec[lid]['ca'] + 0.05 < c < sec[lid]['cb'] - 0.05
    mp = lambda lid, c: maps[lid](c) if lid in maps else c

    # the re-pathed lines: path, ground, stations, trunks, rivers
    newP = dict(oldP)
    for lid, s in sec.items():
        d = D[by_id[lid]]
        old = d['path']
        path = [[round(mp(lid, p[0]), 1), p[1], p[2]] for p in old if p[0] < s['ca'] - 0.05]
        c = s['ca']
        for i, q in enumerate(s['pts']):
            if i:
                c += math.dist(q, s['pts'][i - 1])
            lon, lat = TO_LL.transform(*q)
            path.append([round(c, 1), round(lon, 7), round(lat, 7)])
        path += [[round(p[0] + s['delta'], 1), p[1], p[2]] for p in old if p[0] > s['cb'] + 0.05]
        d['path'] = path
        d['length_m'] = round(d['length_m'] + s['delta'], 1)
        d['route_chainage_m'] = [d['route_chainage_m'][0], round(d['route_chainage_m'][0] + d['length_m'], 1)]
        NP = newP[lid] = Path(path)
        # ground: re-sampled inside the section, moved outside it
        st = d['step_m']
        n = math.ceil(d['length_m'] / st) + 1
        cs = np.minimum(np.arange(n) * st, d['length_m'])
        og = np.array([np.nan if v is None else v for v in d['ground_dm']], float)
        oc = np.arange(len(og)) * st
        gs = sample(np.array([NP.at(c) for c in cs]))
        g = []
        for c, v in zip(cs, gs):
            if c < s['ca'] or c > s['ca'] + s['dn']:
                v = np.interp(c if c < s['ca'] else c - s['delta'], oc, og) / 10
            g.append(None if not np.isfinite(v) else int(round(v * 10)))
        d['ground_dm'] = g
        d['ground_note'] += (f"; old c {s['ca']:.0f}-{s['cb']:.0f} re-pathed onto the Mill Creek Deck's B/D route "
                             f"({s['dn']:.0f} m, 2026-10-27, tools/repath_rer_bd_trunk.py), sampled from the same raster")
        for x in d['stations']:
            if insec(lid, x['c']) and x['name'] in dst:
                q = dst[x['name']]
                c = NP.chain(q)
                lon, lat = TO_LL.transform(*q)
                x.update(c=round(c, 1), lon=round(lon, 7), lat=round(lat, 7), offset=round(NP.L.distance(Point(q)), 1),
                         ground=round(float(sample([NP.at(c)])[0]), 2))
            elif insec(lid, x['c']):
                sys.exit(f"{lid}: {x['name']} is in the section but not a Deck B/D station")
            else:
                x['c'] = round(mp(lid, x['c']), 1)
        for t in d['trunks'] + d['rivers']:
            t['c0'], t['c1'] = round(mp(lid, t['c0']), 1), round(mp(lid, t['c1']), 1)
        print(lid, 'stations', [(x['name'], x['c'], x['offset']) for x in d['stations'] if s['ca'] - 1 < x['c'] < s['ca'] + s['dn'] + 1])

    # crossings: drop those on a section (either side), move the rest, then intersect each new section
    oldfor = {}
    for fn, d in D.items():
        X, xs = d['id'], []
        for x in d.get('crossings', []):
            W = x.get('wid') or {'RER-2': 'RER_2', 'RER-4': 'RER_4'}.get(x.get('with'))
            if W in sec and 'oc' not in x:    # a Metro line's entry: find it on the old RER path
                oc = oldP[W].chain(oldP[X].at(x['c']))
            else:
                oc = x.get('oc')
            if insec(X, x['c']) or (W in sec and oc is not None and insec(W, oc)):
                continue
            y = dict(x, c=round(mp(X, x['c']), 1))
            if 'oc' in x and W:
                y['oc'] = round(mp(W, x['oc']), 1)
            xs.append(y)
        oldfor[fn] = xs
    added = []
    for lid, s in sec.items():
        piece = LineString(s['pts'])
        for fn, d in D.items():
            W = d['id']
            if W == lid:
                continue
            hit = newP[W].L.intersection(piece)
            for p in getattr(hit, 'geoms', [hit]):
                if p.is_empty or p.geom_type != 'Point':
                    continue
                cl, cw = newP[lid].chain((p.x, p.y)), newP[W].chain((p.x, p.y))
                if W in sec and sec[W]['ca'] - 1 < cw < sec[W]['ca'] + sec[W]['dn'] + 1:
                    continue    # B and D on the same route: they part, they do not cross
                rer_w = W.startswith('RER_')
                me = D[by_id[lid]]
                oldfor[by_id[lid]].append({'c': round(cl, 1), 'wid': W, 'oc': round(cw, 1), 'kind': 'rer' if rer_w else 'metro', 'with': d['line']})
                oldfor[fn].append({'c': round(cw, 1), 'wid': lid, 'oc': round(cl, 1), 'kind': 'rer', 'with': me['line']} if rer_w
                                  else {'c': round(cw, 1), 'kind': 'rer', 'with': me['line']})
                added.append((lid, round(cl), d['line']))
    print('new crossings:', added)
    for fn, d in D.items():
        xs = sorted(oldfor[fn], key=lambda x: x['c'])
        if d['id'] in sec or xs != d.get('crossings', []):
            d['crossings'] = xs
            jsave(fn, d)
            oldfor[fn] = None   # written

    # line index, plan networks, the repo's saved RER-2 profile, the chainage map
    idx = jload(SITE + '/rer/lines/index.json')
    for e in idx:
        if e['id'] in sec:
            e['length_m'] = D[by_id[e['id']]]['length_m']
    jsave(SITE + '/rer/lines/index.json', idx)
    net = jload(SITE + '/rer/network.json')
    for lid, s in sec.items():
        pts = net['rer'][lid]
        cc = [oldP[lid].chain(TO_UTM.transform(*q)) for q in pts]
        mid = [[round(v, 7) for v in TO_LL.transform(*q)] for q in LineString(s['pts']).simplify(1.0).coords]
        net['rer'][lid] = [q for q, c in zip(pts, cc) if c < s['ca'] - 0.05] + mid + [q for q, c in zip(pts, cc) if c > s['cb'] + 0.05]
    jsave(SITE + '/rer/network.json', net)
    al = SITE + '/rer/alignments/RER_2.json'
    a = jload(al)
    if a['length_m'] == sec['RER_2']['L0']:
        a['pvi'] = [[round(mp('RER_2', c), 1), z] for c, z in a['pvi']]
        a['ovr'] = [[round(mp('RER_2', c0), 1), round(mp('RER_2', c1), 1), *r] for c0, c1, *r in a['ovr']]
        a['length_m'] = D[by_id['RER_2']]['length_m']
        nst = {x['name']: x['c'] for x in D[by_id['RER_2']]['stations']}
        for x in a.get('stations', []):
            if x['name'] in nst:
                x['point_c'] = x['c'] = nst[x['name']]
        jsave(al, a, indent=2)
    written = sorted({fn.replace(SITE + '/', '') for fn in D if oldfor[fn] is None}
                     | {'rer/lines/index.json', 'rer/network.json'})
    jsave(MAP, {'files': written, 'note': 'RER-2 and RER-4 re-pathed onto the Mill Creek Deck B/D route (tools/repath_rer_bd_trunk.py, 2026-10-27). '
                        'A chainage c on the old path maps to c (c <= ca), ca + (c - ca) * dn / (cb - ca) (ca < c < cb), c + delta (c >= cb).',
                **{lid: {k: round(s[k], 1) for k in ('ca', 'cb', 'dn', 'delta', 'L0')} for lid, s in sec.items()}}, indent=1)
    print('written; now run tools/make_rer4_upper.py and tools/make_profile_context.py')


if __name__ == '__main__':
    main()
