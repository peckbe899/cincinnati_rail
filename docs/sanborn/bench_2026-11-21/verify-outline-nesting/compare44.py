"""verify-outline-nesting: compare my plate-44 harness runs with the agent's (21 Nov 2026).

    python compare44.py   -> compare44.json + printed table

Mine: harness/runs/{batch,final}/bench44.json (harness/bench44.py = unchanged copy of bench44/bench44.py; final uses
benchcopy/outlines_bench_final.py, regenerated by make_bench_copy.py from the diff applied to a copy of outlines.py).
Agent's: outline-nesting/runs/{batch_legacy,final}/bench44.json; phase-1 harness: bench44/runs/batch/bench44.json.
"""
import hashlib, json, os
HERE = os.path.dirname(os.path.abspath(__file__)).replace('\\', '/') + '/'
B = HERE + '../'
RUNS = {'mine_batch': HERE + 'harness/runs/batch/', 'mine_final': HERE + 'harness/runs/final/',
        'bench44_batch': B + 'bench44/runs/batch/', 'agent_batch_legacy': B + 'outline-nesting/runs/batch_legacy/', 'agent_final': B + 'outline-nesting/runs/final/'}
KEYS = ['PQ', 'SQ', 'RQ', 'matched', 'fp', 'merges', 'PQ_decided', 'recall_interior', 'precision', 'precision_green', 'precision_orange', 'ben_blocks_closed', 'intact_rings', 'delete_len', 'draw_len']
sha = lambda p: hashlib.sha256(open(p, 'rb').read()).hexdigest()[:16] if os.path.exists(p) else None
out = {}
for k, d in RUNS.items():
    j = json.load(open(d + 'bench44.json'))
    ls = j['lines_shown']['all']
    out[k] = dict(outlines_sha=sha(d + 'outlines.json'), edges_sha=sha(d + '44_edges.json'), shown_sha=sha(d + '44_shown.json'),
                  headline={f: {x: j['headline'][f][x] for x in KEYS} for f in ('all', 'A', 'B')},
                  decided=dict(recall=ls.get('recall_interior_decided'), precision=ls.get('precision_decided')),
                  tol=ls.get('tol_sensitivity'), workload_all=j['workload']['all'], counts=json.load(open(d + 'outline_step.json'))['rep'])
json.dump(out, open(HERE + 'compare44.json', 'w'), indent=1)
for f in ('all', 'A', 'B'):
    print(f'--- fold {f}')
    print(f"{'key':18s}" + ''.join(f'{k:>20s}' for k in RUNS))
    for x in KEYS: print(f'{x:18s}' + ''.join(f"{str(out[k]['headline'][f][x]):>20s}" for k in RUNS))
print('decided   ' + ' | '.join(f"{k}: {out[k]['decided']}" for k in RUNS))
for k in RUNS: print('tol', k, out[k]['tol'])
for k in RUNS: print('sha', k, out[k]['outlines_sha'], out[k]['edges_sha'], out[k]['shown_sha'])
for k in RUNS: print('counts', k, {x: out[k]['counts'].get(x) for x in ('blocks', 'holes', 'holes_in_open_land', 'sides', 'share_on_printed_line_by_length', 'suspect', 'suspect_why')}, out[k]['counts'].get('qa'))
