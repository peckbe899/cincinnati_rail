CELL = 250


def built_up(p):
    im = plate_img(p); pp = paper(p); H, W = pp.shape
    hsv = cv2.cvtColor(cv2.resize(im, (W // 4, H // 4), interpolation=cv2.INTER_AREA), cv2.COLOR_BGR2HSV)
    h, s = hsv[..., 0].astype(int), hsv[..., 1].astype(int)
    fill = (((h < 12) | (h > 160)) & (s > 50)) | ((h >= 15) & (h <= 32) & (s > 100))
    pq = cv2.resize(pp.astype(np.uint8), (W // 4, H // 4), interpolation=cv2.INTER_NEAREST) > 0
    fill &= pq; c = CELL // 4
    cells = []
    for gy in range(0, H // 4 - c + 1, c):
        for gx in range(0, W // 4 - c + 1, c):
            if pq[gy:gy + c, gx:gx + c].mean() >= 0.95 and fill[gy:gy + c, gx:gx + c].mean() >= 0.05: cells.append((gx * 4, gy * 4))
    return cells, fill, pq


def win_ok(pq, fill, x0, y0, x1, y1, minfill=0.0):
    H, W = pq.shape
    if x0 < 0 or y0 < 0 or x1 > W * 4 or y1 > H * 4: return False
    q = pq[y0 // 4:y1 // 4, x0 // 4:x1 // 4]
    return bool(q.mean() >= 0.99 and fill[y0 // 4:y1 // 4, x0 // 4:x1 // 4].mean() >= minfill)


def overlap(a, b): return not (a[2] <= b[0] or b[2] <= a[0] or a[3] <= b[1] or b[3] <= a[1])


def main():
    rounds = int(sys.argv[sys.argv.index('--rounds') + 1]) if '--rounds' in sys.argv else 1
    out = dict(blocks={}, full=None, ditto={})
    for p in SCALE:
        rng = random.Random(p); order = rng.sample(CANDS[p], len(CANDS[p]))
        out['blocks'][p] = dict(seed=p, k=K[p], candidates=CANDS[p], drawn_order=order)
    rng = random.Random('SB-F1'); p = rng.choice(['56', '58', '63'])
    cells, fill, pq = built_up(p); tries = []
    while True:
        cx, cy = rng.choice(cells); x0 = cx + CELL // 2 - 750 + rng.randint(-125, 125); y0 = cy + CELL // 2 - 500 + rng.randint(-125, 125)
        w = [x0, y0, x0 + 1500, y0 + 1000]; ok = win_ok(pq, fill, *w, minfill=0.04); tries.append(dict(win=w, ok=ok))
        if ok: break
    out['full'] = dict(seed='SB-F1', plate=p, win=w, built_up_cells=len(cells), tries=tries)
    for p in SCALE:
        cells, fill, pq = built_up(p)
        rng = random.Random(f'ditto-{p}'); wins = []; tries = []
        need = rounds if p == '92' else 2 * rounds
        while len(wins) < need:
            cx, cy = rng.choice(cells); mx, my = cx + rng.randint(0, CELL - 1), cy + rng.randint(0, CELL - 1)
            w = [mx - 250, my - 200, mx + 250, my + 200]
            ok = win_ok(pq, fill, *w) and not any(overlap(w, v) for v in wins) and not (p == out['full']['plate'] and overlap(w, out['full']['win']))
            tries.append(dict(win=w, ok=bool(ok)))
            if ok: wins.append(w)
        out['ditto'][p] = dict(seed=f'ditto-{p}', windows=wins, tries=tries, built_up_cells=len(cells))
        print(p, 'built-up cells', len(cells), 'ditto windows', wins)
    print('full', out['full']['plate'], out['full']['win'], 'tries', len(out['full']['tries']))
    for p in SCALE: print('blocks', p, [c['label'] + c['note'] for c in out['blocks'][p]['drawn_order']])
    jdump(out, os.path.join(INV, 'truth', 'annot', 'selection.json'))


if __name__ == '__main__':
    main()
